CREATE TABLE storage_space (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket_name VARCHAR(63) COLLATE "C" NOT NULL,
    region_id VARCHAR(32) COLLATE "C" NOT NULL,
    access_domain VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT uk_storage_space_bucket_name UNIQUE (bucket_name)
);

CREATE TABLE storage_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(10) COLLATE "C" NOT NULL,
    space_id BIGINT,
    storage_key VARCHAR(1024) COLLATE "C" NOT NULL,
    content_type VARCHAR(127) COLLATE "C" NOT NULL,
    size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT chk_storage_file_destination CHECK (
        (provider = 'local' AND space_id IS NULL)
        OR (provider = 'aliyun' AND space_id IS NOT NULL)
    ),
    CONSTRAINT chk_storage_file_key_length CHECK (OCTET_LENGTH(storage_key) BETWEEN 1 AND 1023),
    CONSTRAINT chk_storage_file_size CHECK (size_bytes >= 0)
);
CREATE INDEX idx_storage_file_space_id ON storage_file (space_id);

CREATE FUNCTION atlas_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := LOCALTIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sys_user_updated_at BEFORE UPDATE ON sys_user
FOR EACH ROW EXECUTE FUNCTION atlas_touch_updated_at();
CREATE TRIGGER trg_user_account_updated_at BEFORE UPDATE ON user_account
FOR EACH ROW EXECUTE FUNCTION atlas_touch_updated_at();
CREATE TRIGGER trg_sys_config_updated_at BEFORE UPDATE ON sys_config
FOR EACH ROW EXECUTE FUNCTION atlas_touch_updated_at();
CREATE TRIGGER trg_storage_space_updated_at BEFORE UPDATE ON storage_space
FOR EACH ROW EXECUTE FUNCTION atlas_touch_updated_at();
CREATE TRIGGER trg_storage_file_updated_at BEFORE UPDATE ON storage_file
FOR EACH ROW EXECUTE FUNCTION atlas_touch_updated_at();

COMMENT ON TABLE sys_user IS '后台系统用户表';
COMMENT ON TABLE user_account IS '普通用户账号表';
COMMENT ON TABLE sys_config IS '系统配置表';
COMMENT ON TABLE storage_space IS '阿里云OSS空间绑定表，不代表创建或删除云端Bucket';
COMMENT ON TABLE storage_file IS '上传文件表，记录实际存储位置，不受全局存储切换影响';
