CREATE TABLE user_account (
    id BIGINT PRIMARY KEY,
    user_no VARCHAR(32) NOT NULL,
    phone VARCHAR(20),
    email VARCHAR(100),
    password VARCHAR(100),
    password_version BIGINT NOT NULL DEFAULT 0,
    nickname VARCHAR(50),
    avatar VARCHAR(255),
    status SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT uk_user_account_user_no UNIQUE (user_no),
    CONSTRAINT uk_user_account_phone UNIQUE (phone),
    CONSTRAINT uk_user_account_email UNIQUE (email),
    CONSTRAINT chk_user_account_status CHECK (status IN (0, 1)),
    CONSTRAINT chk_user_account_password_version CHECK (password_version >= 0)
);
CREATE INDEX idx_user_account_status ON user_account (status);

CREATE TABLE sys_config (
    config_key VARCHAR(100) PRIMARY KEY,
