CREATE TABLE sms_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(10) NOT NULL,
    name VARCHAR(80) NOT NULL,
    template_code VARCHAR(100) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    content VARCHAR(1000) NOT NULL,
    variables_json TEXT NOT NULL DEFAULT '[]',
    review_status VARCHAR(20) NOT NULL DEFAULT 'pending',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT chk_sms_template_provider CHECK (provider IN ('aliyun', 'tencent')),
    CONSTRAINT chk_sms_template_kind CHECK (kind IN ('verification', 'notification', 'marketing')),
    CONSTRAINT chk_sms_template_review_status CHECK (review_status IN ('pending', 'approved', 'rejected')),
    CONSTRAINT uk_sms_template_provider_code UNIQUE (provider, template_code)
);

CREATE INDEX idx_sms_template_provider_kind ON sms_template (provider, kind);
CREATE INDEX idx_sms_template_updated_at ON sms_template (updated_at DESC, id DESC);

CREATE TRIGGER trg_sms_template_updated_at BEFORE UPDATE ON sms_template
FOR EACH ROW EXECUTE FUNCTION atlas_touch_updated_at();

COMMENT ON TABLE sms_template IS '阿里云和腾讯云短信模板登记；不向服务商提交模板审核';
COMMENT ON COLUMN sms_template.variables_json IS '模板变量名称 JSON 数组';
