-- Persist message notification scenario configuration for the existing Atlas channels.
-- This migration stores channel/template settings only; business event dispatch remains a separate concern.

CREATE TABLE message_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(16) NOT NULL,
    code VARCHAR(80) NOT NULL,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(200) NOT NULL,
    site_message_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    sms_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    site_message_title VARCHAR(120) NOT NULL DEFAULT '',
    site_message_content TEXT NOT NULL DEFAULT '',
    sms_template_id BIGINT,
    sms_variable_mappings JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT chk_message_notification_category CHECK (category IN ('member', 'platform', 'custom')),
    CONSTRAINT uk_message_notification_category_code UNIQUE (category, code),
    CONSTRAINT fk_message_notification_sms_template
        FOREIGN KEY (sms_template_id) REFERENCES sms_template(id) ON DELETE SET NULL
);

CREATE INDEX idx_message_notification_category_id ON message_notification(category, id);
CREATE INDEX idx_message_notification_sms_template ON message_notification(sms_template_id)
    WHERE sms_template_id IS NOT NULL;

CREATE TRIGGER trg_message_notification_updated_at BEFORE UPDATE ON message_notification
FOR EACH ROW EXECUTE FUNCTION atlas_touch_updated_at();

