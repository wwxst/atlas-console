-- PostgreSQL 17 draft schema for the future AI gateway.
-- This file is for independent review only; it is not part of the active Flyway V1 migration.
-- Keep this design separate until the AI gateway feature is implemented and reviewed.
-- The domains preserve nonnegative unsigned intent within PostgreSQL's supported numeric ranges.

CREATE DOMAIN ai_gateway_nonnegative_bigint AS BIGINT CHECK (VALUE >= 0);
CREATE DOMAIN ai_gateway_nonnegative_integer AS BIGINT CHECK (VALUE BETWEEN 0 AND 4294967295);

/**
 * 多模型付费 API 网关 PostgreSQL 17 数据库结构草案（Sub2API 上游）
 *
 * 本文件用于独立审阅，暂不并入 V1 Flyway 迁移。
 * 遵循当前项目约束：不创建 Foreign Key，表之间通过 ID、唯一键和业务事务关联。此草案仅适用于 PostgreSQL 17。
 */

/* 用户钱包：余额和消费单位为积分，1 CNY = 10 points。 */
CREATE TABLE ai_wallet (
user_id          ai_gateway_nonnegative_bigint NOT NULL,
    available_points ai_gateway_nonnegative_bigint NOT NULL DEFAULT 0,
    reserved_points  ai_gateway_nonnegative_bigint NOT NULL DEFAULT 0,
    created_at           TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at           TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,

    PRIMARY KEY (user_id)
);


/* 用户 API Key：只保存单向 Hash，完整明文只在创建成功时返回一次。 */
CREATE TABLE ai_api_key (
id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id        ai_gateway_nonnegative_bigint NOT NULL,
    name           VARCHAR(100)    NOT NULL,
    key_prefix     VARCHAR(32) COLLATE "C" NOT NULL,
    secret_hash    VARCHAR(255) COLLATE "C" NOT NULL,
    status         VARCHAR(16) COLLATE "C" NOT NULL DEFAULT 'ACTIVE',
    last_used_at   TIMESTAMP WITHOUT TIME ZONE        DEFAULT NULL,
    created_at     TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,
    revoked_at     TIMESTAMP WITHOUT TIME ZONE        DEFAULT NULL,
    updated_at     TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,

    PRIMARY KEY (id),
    CONSTRAINT uk_ai_api_key_secret_hash UNIQUE (secret_hash),

    CONSTRAINT chk_ai_api_key_status CHECK (status IN ('ACTIVE', 'REVOKED'))
);
CREATE INDEX idx_ai_api_key_user_status ON ai_api_key (user_id, status);


/* 上游通道：每个 Sub2API API Key 对应一个通道。 */
CREATE TABLE ai_upstream_channel (
id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name               VARCHAR(100)    NOT NULL,
    channel_type       VARCHAR(32) COLLATE "C" NOT NULL,
    protocol_type      VARCHAR(32) COLLATE "C" NOT NULL,
    base_url           VARCHAR(512)    NOT NULL,
    encrypted_api_key  VARCHAR(1024)   NOT NULL,
    enabled            SMALLINT         NOT NULL DEFAULT 1,
    created_at         TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at         TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,

    PRIMARY KEY (id),
    CONSTRAINT uk_ai_upstream_channel_name UNIQUE (name),

    CONSTRAINT chk_ai_upstream_channel_channel_type CHECK (channel_type IN ('SUB2API')),
    CONSTRAINT chk_ai_upstream_channel_protocol CHECK (protocol_type IN ('CHAT_COMPLETIONS', 'RESPONSES', 'MESSAGES')),
    CONSTRAINT chk_ai_upstream_channel_enabled CHECK (enabled IN (0, 1))
);
CREATE INDEX idx_ai_upstream_channel_channel_type_enabled ON ai_upstream_channel (channel_type, enabled);


/* 用户可见模型与上游模型的映射。 */
CREATE TABLE ai_gateway_model (
id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    public_model         VARCHAR(100) COLLATE "C" NOT NULL,
    model_family         VARCHAR(32) COLLATE "C" NOT NULL,
    upstream_model       VARCHAR(255) COLLATE "C" NOT NULL,
    upstream_channel_id  ai_gateway_nonnegative_bigint NOT NULL,
    enabled              SMALLINT         NOT NULL DEFAULT 1,
    max_input_bytes      ai_gateway_nonnegative_integer    NOT NULL,
    max_output_tokens    ai_gateway_nonnegative_integer    NOT NULL,
    created_at           TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at           TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,

    PRIMARY KEY (id),
    CONSTRAINT uk_ai_gateway_model_public_model UNIQUE (public_model),

    CONSTRAINT chk_ai_gateway_model_enabled CHECK (enabled IN (0, 1)),
    CONSTRAINT chk_ai_gateway_model_limits CHECK (max_input_bytes > 0 AND max_output_tokens > 0)
);
CREATE INDEX idx_ai_gateway_model_channel_enabled ON ai_gateway_model (upstream_channel_id, enabled);


/* 模型分价格档位配置：金额和倍率均使用整数保存。 */
CREATE TABLE ai_model_price (
id                       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    model_id                 ai_gateway_nonnegative_bigint NOT NULL,
    price_band               VARCHAR(16) COLLATE "C" NOT NULL,
    upstream_input_cost_points    ai_gateway_nonnegative_bigint NOT NULL,
    upstream_output_cost_points   ai_gateway_nonnegative_bigint NOT NULL,
    base_input_sale_price_points  ai_gateway_nonnegative_bigint NOT NULL,
    base_output_sale_price_points ai_gateway_nonnegative_bigint NOT NULL,
    billing_multiplier_ppm   ai_gateway_nonnegative_bigint NOT NULL DEFAULT 1000000,
    created_at               TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_at               TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,

    PRIMARY KEY (id),
    CONSTRAINT uk_ai_model_price_model_band UNIQUE (model_id, price_band),

    CONSTRAINT chk_ai_model_price_band CHECK (price_band IN ('STANDARD', 'PEAK', 'OFF_PEAK')),
    CONSTRAINT chk_ai_model_price_multiplier CHECK (billing_multiplier_ppm > 0)
);
CREATE INDEX idx_ai_model_price_band ON ai_model_price (price_band);


/* 一次网关请求：保存路由、价格、倍率和结算快照。 */
CREATE TABLE ai_gateway_request (
id                              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_id                      VARCHAR(64) COLLATE "C" NOT NULL,
    idempotency_key                 VARCHAR(255) COLLATE "C" DEFAULT NULL,
    user_id                         ai_gateway_nonnegative_bigint NOT NULL,
    public_model                    VARCHAR(100) COLLATE "C" NOT NULL,
    model_family                    VARCHAR(32) COLLATE "C" NOT NULL,
    upstream_model                  VARCHAR(255) COLLATE "C" NOT NULL,
    upstream_channel_id             ai_gateway_nonnegative_bigint NOT NULL,
    endpoint_type                   VARCHAR(32) COLLATE "C" NOT NULL,
    price_band                      VARCHAR(16) COLLATE "C" NOT NULL,
    upstream_input_cost_points_snapshot    ai_gateway_nonnegative_bigint NOT NULL,
    upstream_output_cost_points_snapshot   ai_gateway_nonnegative_bigint NOT NULL,
    base_input_sale_price_points_snapshot  ai_gateway_nonnegative_bigint NOT NULL,
    base_output_sale_price_points_snapshot ai_gateway_nonnegative_bigint NOT NULL,
    billing_multiplier_ppm_snapshot ai_gateway_nonnegative_bigint NOT NULL,
    user_input_price_points_snapshot  ai_gateway_nonnegative_bigint NOT NULL,
    user_output_price_points_snapshot ai_gateway_nonnegative_bigint NOT NULL,
    reserved_points                    ai_gateway_nonnegative_bigint NOT NULL DEFAULT 0,
    input_tokens                    ai_gateway_nonnegative_bigint DEFAULT NULL,
    output_tokens                   ai_gateway_nonnegative_bigint DEFAULT NULL,
    total_tokens                    ai_gateway_nonnegative_bigint DEFAULT NULL,
    upstream_cost_points             ai_gateway_nonnegative_bigint DEFAULT NULL,
    user_charge_points               ai_gateway_nonnegative_bigint DEFAULT NULL,
    margin_points                    BIGINT          DEFAULT NULL,
    upstream_request_id             VARCHAR(255) COLLATE "C" DEFAULT NULL,
    status                          VARCHAR(32) COLLATE "C" NOT NULL,
    failure_code                    VARCHAR(64) COLLATE "C" DEFAULT NULL,
    created_at                      TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,
    completed_at                    TIMESTAMP WITHOUT TIME ZONE        DEFAULT NULL,

    PRIMARY KEY (id),
    CONSTRAINT uk_ai_gateway_request_request_id UNIQUE (request_id),
    CONSTRAINT uk_ai_gateway_request_user_idempotency UNIQUE (user_id, idempotency_key),

    CONSTRAINT chk_ai_gateway_request_endpoint CHECK (endpoint_type IN ('CHAT_COMPLETIONS', 'RESPONSES', 'MESSAGES')),
    CONSTRAINT chk_ai_gateway_request_price_band CHECK (price_band IN ('STANDARD', 'PEAK', 'OFF_PEAK')),
    CONSTRAINT chk_ai_gateway_request_status CHECK (status IN ('RESERVED', 'SETTLED', 'RELEASED', 'UPSTREAM_FAILED', 'USAGE_MISSING'))
);
CREATE INDEX idx_ai_gateway_request_user_created ON ai_gateway_request (user_id, created_at);
CREATE INDEX idx_ai_gateway_request_model_created ON ai_gateway_request (public_model, created_at);
CREATE INDEX idx_ai_gateway_request_status_created ON ai_gateway_request (status, created_at);


/* 独立用量统计：只读取此表中的快照，不回读当前价格配置。 */
