    public_model                    VARCHAR(100) COLLATE "C" NOT NULL,
    model_family                    VARCHAR(32) COLLATE "C" NOT NULL,
    upstream_model                  VARCHAR(255) COLLATE "C" NOT NULL,
    upstream_channel_id             ai_gateway_nonnegative_bigint NOT NULL,
    endpoint_type                   VARCHAR(32) COLLATE "C" NOT NULL,
    price_band                      VARCHAR(16) COLLATE "C" NOT NULL,
    upstream_input_cost_points_snapshot    ai_gateway_nonnegative_bigint NOT NULL,
    upstream_output_cost_points_snapshot   ai_gateway_nonnegative_bigint NOT NULL,
    base_input_sale_price_points_snapshot  ai_gateway_nonnegative_bigint NOT NULL,
    base_output_sale_price_points_snapshot ai_gateway_nonnegative_bigint NOT NULL,
    billing_multiplier_ppm_snapshot ai_gateway_nonnegative_bigint NOT NULL,
    user_input_price_points_snapshot  ai_gateway_nonnegative_bigint NOT NULL,
    user_output_price_points_snapshot ai_gateway_nonnegative_bigint NOT NULL,
    input_tokens                    ai_gateway_nonnegative_bigint NOT NULL DEFAULT 0,
    output_tokens                   ai_gateway_nonnegative_bigint NOT NULL DEFAULT 0,
    total_tokens                    ai_gateway_nonnegative_bigint NOT NULL DEFAULT 0,
    upstream_cost_points             ai_gateway_nonnegative_bigint NOT NULL DEFAULT 0,
    user_charge_points               ai_gateway_nonnegative_bigint NOT NULL DEFAULT 0,
    margin_points                    BIGINT          NOT NULL DEFAULT 0,
    status                          VARCHAR(32) COLLATE "C" NOT NULL,
    created_at                      TIMESTAMP WITHOUT TIME ZONE        NOT NULL DEFAULT LOCALTIMESTAMP,

    PRIMARY KEY (id),
    CONSTRAINT uk_ai_usage_record_request_id UNIQUE (request_id),

    CONSTRAINT chk_ai_usage_record_endpoint CHECK (endpoint_type IN ('CHAT_COMPLETIONS', 'RESPONSES', 'MESSAGES')),
    CONSTRAINT chk_ai_usage_record_price_band CHECK (price_band IN ('STANDARD', 'PEAK', 'OFF_PEAK')),
    CONSTRAINT chk_ai_usage_record_status CHECK (status IN ('SETTLED', 'USAGE_MISSING'))
);
CREATE INDEX idx_ai_usage_record_user_created ON ai_usage_record (user_id, created_at);
CREATE INDEX idx_ai_usage_record_model_created ON ai_usage_record (public_model, created_at);
CREATE INDEX idx_ai_usage_record_channel_created ON ai_usage_record (upstream_channel_id, created_at);


/* 不可变账务流水：积分变化有符号，支持充值、扣费、退款和管理员调整。 */
CREATE TABLE ai_billing_transaction (
id                    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id               ai_gateway_nonnegative_bigint NOT NULL,
    request_id            VARCHAR(64) COLLATE "C" DEFAULT NULL,
    transaction_type      VARCHAR(20) COLLATE "C" NOT NULL,
    amount_change_points  BIGINT NOT NULL,
    balance_after_points  ai_gateway_nonnegative_bigint NOT NULL,
    recharge_amount_fen  ai_gateway_nonnegative_bigint DEFAULT NULL,
    operation_id          VARCHAR(128) COLLATE "C" DEFAULT NULL,
    operator_user_id      ai_gateway_nonnegative_bigint DEFAULT NULL,
    description           VARCHAR(255) DEFAULT NULL,
    created_at            TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,

    PRIMARY KEY (id),
    CONSTRAINT uk_ai_billing_transaction_request_type UNIQUE (request_id, transaction_type),
    CONSTRAINT uk_ai_billing_transaction_operation UNIQUE (operation_id),

    CONSTRAINT chk_ai_billing_transaction_type CHECK (transaction_type IN ('TOP_UP', 'CONSUMPTION', 'REFUND', 'ADJUSTMENT')),
    CONSTRAINT chk_ai_billing_transaction_amount CHECK (amount_change_points <> 0)
);
CREATE INDEX idx_ai_billing_transaction_user_created ON ai_billing_transaction (user_id, created_at);
CREATE INDEX idx_ai_billing_transaction_type_created ON ai_billing_transaction (transaction_type, created_at);


-- Preserve automatic updated_at behavior using PostgreSQL triggers.
CREATE OR REPLACE FUNCTION ai_gateway_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := LOCALTIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_ai_wallet_updated_at BEFORE UPDATE ON ai_wallet
FOR EACH ROW EXECUTE FUNCTION ai_gateway_touch_updated_at();
CREATE TRIGGER trg_ai_api_key_updated_at BEFORE UPDATE ON ai_api_key
FOR EACH ROW EXECUTE FUNCTION ai_gateway_touch_updated_at();
CREATE TRIGGER trg_ai_upstream_channel_updated_at BEFORE UPDATE ON ai_upstream_channel
FOR EACH ROW EXECUTE FUNCTION ai_gateway_touch_updated_at();
CREATE TRIGGER trg_ai_gateway_model_updated_at BEFORE UPDATE ON ai_gateway_model
FOR EACH ROW EXECUTE FUNCTION ai_gateway_touch_updated_at();
CREATE TRIGGER trg_ai_model_price_updated_at BEFORE UPDATE ON ai_model_price
FOR EACH ROW EXECUTE FUNCTION ai_gateway_touch_updated_at();

